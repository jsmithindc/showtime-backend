// Generates lib/us-map-path.js -- the contiguous-US state outline as SVG path
// data, already projected by lib/us-map.js.
//
// Run: node scripts/build-us-map-path.js --write
//
// Baked at build time rather than fetched at runtime: the shape of the country
// does not change, and a map that needs a network call to draw itself would be
// one more thing to fail mid-search.
//
// Source: PublicaMundi/MappingAPI us-states.json, itself derived from US Census
// Bureau cartographic boundary files -- US government work, public domain.
const fs = require("fs");
const path = require("path");
const fetch = require("node-fetch");
const { project } = require("../lib/us-map");

const SOURCE = "https://raw.githubusercontent.com/PublicaMundi/MappingAPI/master/data/geojson/us-states.json";
const SKIP = new Set(["Alaska", "Hawaii", "Puerto Rico"]);   // lib/us-map.js is CONUS-only

// Drop points closer than this (in projected units) to the previous kept one.
// The raw outline is far more detailed than a 960px-wide map can show, and the
// difference is measured below rather than assumed.
const MIN_STEP = 1.5;

function ringToPath(ring) {
  const out = [];
  let last = null;
  for (const [lng, lat] of ring) {
    const [x, y] = project(lat, lng);
    if (last && Math.abs(x - last[0]) < MIN_STEP && Math.abs(y - last[1]) < MIN_STEP) continue;
    out.push([x, y]);
    last = [x, y];
  }
  if (out.length < 3) return null;
  return "M" + out.map((p) => p.join(" ")).join("L") + "Z";
}

(async () => {
  const res = await fetch(SOURCE, { timeout: 30000 });
  if (!res.ok) throw new Error(`source fetch failed: ${res.status}`);
  const geo = await res.json();

  const paths = [];
  let rawPoints = 0;
  for (const f of geo.features) {
    if (SKIP.has(f.properties.name)) continue;
    const g = f.geometry;
    const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys) {
      for (const ring of poly) {
        rawPoints += ring.length;
        const d = ringToPath(ring);
        if (d) paths.push(d);
      }
    }
  }

  const d = paths.join("");
  const body = `// GENERATED by scripts/build-us-map-path.js -- do not hand-edit.
// Contiguous US state outlines, projected by lib/us-map.js (Albers conic).
// Source: US Census Bureau cartographic boundaries (public domain), via
// PublicaMundi/MappingAPI. Regenerate with:
//   node scripts/build-us-map-path.js --write
module.exports = ${JSON.stringify(d)};
`;
  console.log(`states kept: ${paths.length} ring(s)`);
  console.log(`points: ${rawPoints} raw -> ${(d.match(/L/g) || []).length + paths.length} kept`);
  console.log(`path size: ${(body.length / 1024).toFixed(1)}KB`);

  if (process.argv.includes("--write")) {
    fs.writeFileSync(path.join(__dirname, "..", "lib", "us-map-path.js"), body);
    console.log("wrote lib/us-map-path.js");
  } else {
    console.log("(dry run -- pass --write to save)");
  }
})();
