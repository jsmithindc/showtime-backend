// Generates lib/celebration-cinemas.js -- every Celebration! Cinema location
// with its coordinates and Vista cinema id.
//
// Run: node scripts/build-celebration-cinemas.js --write
//
// Static list with a generator, the same pattern as Alamo: a hand-maintained
// list is only as good as whoever last edited it (Alamo sat at 22 of 40 for
// months with nothing to indicate the gap), while regenerating from the
// chain's own pages is cheap and self-correcting.
//
// Two things are read from each cinema page:
//   - schema.org JSON-LD, which states name, street address AND geo
//     coordinates, so nothing has to be geocoded and none of the
//     "geocoded to the wrong plaza" failures in CLAUDE.md apply.
//   - the DOMINANT session-id prefix, which is that cinema's Vista id. Pages
//     carry a few stray ids from other locations (cross-references in
//     disabledshowtimes); on GR North its own "002" appeared 3549 times
//     against 1-9 for six others, so "most frequent" is unambiguous.
const fs = require("fs");
const path = require("path");
const fetch = require("node-fetch");
const { parseSessions } = require("../lib/priceAdapters/celebration-official");

const BASE = "https://www.celebrationcinema.com";
const GAP_MS = 3000;   // the pages are ~2.3MB and the site refuses rapid bursts

async function getHtml(url) {
  const res = await fetch(url, { timeout: 60000 });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
  return res.text();
}

function extractJsonLd(html) {
  for (const m of html.matchAll(/<script[^>]*application\/ld\+json[^>]*>([\s\S]*?)<\/script>/gi)) {
    try {
      const parsed = JSON.parse(m[1]);
      for (const o of (Array.isArray(parsed) ? parsed : [parsed])) {
        if (o && o.geo && o.address) return o;
      }
    } catch { /* a page may carry unrelated or malformed blocks */ }
  }
  return null;
}

// Counted over PARSED SESSIONS, not raw "NNN-NNNNNN" strings anywhere in the
// page. Every cinema page carries a fixed block of 66 cross-references to
// GR North's "002" (the disabledshowtimes list), which for a small venue can
// outnumber its own sessions: Getty Drive-In has 61 real ones and was
// confidently mislabelled 002 -- GR North's id -- by a raw string count.
// Session objects are the page's actual schedule, so cross-references can't
// contaminate them.
function dominantCinemaId(html) {
  const counts = {};
  for (const s of parseSessions(html, null)) {
    counts[s.cinemaId] = (counts[s.cinemaId] || 0) + 1;
  }
  const ranked = Object.entries(counts).sort((a, b) => b[1] - a[1]);
  return ranked.length ? { id: ranked[0][0], count: ranked[0][1], runnerUp: ranked[1] || null } : null;
}

(async () => {
  const home = await getHtml(`${BASE}/`);
  const slugs = [...new Set((home.match(/\/cinemas\/[A-Za-z0-9\-]+/g) || []).map((s) => s.replace("/cinemas/", "")))];
  console.log(`found ${slugs.length} cinema slug(s) on the homepage`);

  const cinemas = [];
  for (const slug of slugs) {
    try {
      const html = await getHtml(`${BASE}/cinemas/${slug}`);
      const ld = extractJsonLd(html);
      const cid = dominantCinemaId(html);
      if (!ld || !cid) { console.log(`  SKIP ${slug} (jsonLd:${!!ld} cinemaId:${!!cid})`); continue; }
      cinemas.push({
        slug,
        cinemaId: cid.id,
        name: String(ld.name).replace(/^["\s]+|["\s]+$/g, ""),
        address: ld.address.streetAddress,
        city: ld.address.addressLocality,
        state: ld.address.addressRegion,
        lat: Number(ld.geo.latitude),
        lng: Number(ld.geo.longitude),
      });
      console.log(`  ${slug.padEnd(34)} id=${cid.id} (${cid.count} sessions, next ${cid.runnerUp ? cid.runnerUp.join(":") : "-"})  ${ld.name}`);
    } catch (err) {
      console.log(`  FAIL ${slug}: ${err.message}`);
    }
    await new Promise((r) => setTimeout(r, GAP_MS));
  }

  const body = `// GENERATED by scripts/build-celebration-cinemas.js -- do not hand-edit.
// Celebration! Cinema locations, with coordinates from each page's own
// schema.org JSON-LD and the Vista cinema id from its dominant session prefix.
// Regenerate with: node scripts/build-celebration-cinemas.js --write
module.exports = ${JSON.stringify(cinemas, null, 2)};
`;
  console.log(`\n${cinemas.length}/${slugs.length} cinemas resolved`);
  if (process.argv.includes("--write")) {
    fs.writeFileSync(path.join(__dirname, "..", "lib", "celebration-cinemas.js"), body);
    console.log("wrote lib/celebration-cinemas.js");
  } else {
    console.log("(dry run -- pass --write to save)");
  }
})();
